"""Brachistochrone: minimum-time slide under gravity (Bernoulli 1696).

Problem (y positive *downward*, g=1)::

    minimize   tf
    subject to dx/dt = v sin(θ)
               dy/dt = v cos(θ)
               dv/dt = g cos(θ)
               (x,y,v)(0) = (0,0,0)
               (x,y)(tf) = (π, 2)
               0 <= θ <= π
               tf free

``θ`` is the heading from the downward vertical: θ=0 is free fall,
θ=π/2 is horizontal. Energy gives ``v = sqrt(2 g y)`` along any
frictionless wire; the OCP chooses the *shape* that minimises time.

Analytic solution
-----------------
The minimiser is a cycloid generated by a circle of radius ``a``.
With the default endpoint ``(π, 2)`` and ``g=1`` one has ``a=1`` and
terminal roll angle ``φ_f = π``, so

    x(φ) = a (φ - sin φ)
    y(φ) = a (1 - cos φ)
    v(φ) = 2 sqrt(g a) |sin(φ/2)|
    θ(φ) = φ/2
    t    = φ sqrt(a/g)

hence ``tf* = π`` and ``θ*(t) = t/2``. See ``README.md`` for the
Pontryagin derivation of ``θ=φ/2`` and the generating-radius fit for
a general endpoint.
"""

import math

import casadi as cs
import numpy as np

import eco_opt
from eco_opt import Namespace

G = 1.0
# Half-cycloid of radius a=1: (xf, yf) = (π, 2), tf* = π.
A = 1.0
PHI_F = math.pi
X_F = A * (PHI_F - math.sin(PHI_F))
Y_F = A * (1.0 - math.cos(PHI_F))
ANALYTIC_TF = PHI_F * math.sqrt(A / G)  # π


def brachistochrone_model(t, x, u, g=G):
    xpos, ypos, speed = x[0], x[1], x[2]
    theta = u[0]
    s = cs.sin(theta)
    c = cs.cos(theta)
    y = Namespace(x=xpos, y=ypos, v=speed, theta=theta)
    return [speed * s, speed * c, g * c], y


def build_ocp(xf=X_F, yf=Y_F, g=G):
    def model(t, x, u):
        return brachistochrone_model(t, x, u, g=g)

    sys = eco_opt.System(states=3, controls=1, model=model, name="brachistochrone")
    ocp = eco_opt.Ocp()
    ocp.min(eco_opt.t_f(sys.t))
    ocp.st(
        system=sys,
        constraints=[
            (0.0, "<=", sys.u[0], "<=", math.pi),
            (0.0, "<=", sys.y.x),
            (0.0, "<=", sys.y.y),
            (0.0, "<=", sys.y.v),
            (0.0, "==", eco_opt.t_0(sys.t)),
            (0.1, "<=", eco_opt.t_f(sys.t), "<=", 20.0),
            (0.0, "==", eco_opt.t_0(sys.y.x)),
            (0.0, "==", eco_opt.t_0(sys.y.y)),
            (0.0, "==", eco_opt.t_0(sys.y.v)),
            (xf, "==", eco_opt.t_f(sys.y.x)),
            (yf, "==", eco_opt.t_f(sys.y.y)),
        ],
    )
    return ocp, sys


def solve(
    xf=X_F,
    yf=Y_F,
    g=G,
    control_intervals=40,
    polynomial_degree=4,
    tf_guess=None,
):
    if tf_guess is None:
        tf_guess = analytic_tf(xf, yf, g)
    ocp, sys = build_ocp(xf=xf, yf=yf, g=g)
    sol = ocp.solve(
        control_intervals=control_intervals,
        polynomial_degree=polynomial_degree,
        collocation_points="legendre",
        initial_guess={
            sys.x[0]: 0.5 * xf,
            sys.x[1]: 0.5 * yf,
            sys.x[2]: math.sqrt(max(g * yf, 1e-6)),
            sys.u[0]: 0.7,
        },
        ipopt_options={"max_iter": 2000, "tol": 1e-8},
        tf_guess=tf_guess,
    )
    return sol, sys


def cycloid_phi_f(xf, yf, tol=1e-14, maxiter=60):
    """Terminal roll angle of the cycloid through (0,0) and (xf, yf)."""
    if yf <= 0.0:
        raise ValueError("yf must be positive (y is downward)")
    target = xf / yf
    phi = 2.5
    for _ in range(maxiter):
        s, c = math.sin(phi), math.cos(phi)
        den = 1.0 - c
        if abs(den) < 1e-16:
            phi = 0.5
            continue
        num = phi - s
        f = num / den - target
        df = ((1.0 - c) * den - num * s) / (den * den)
        phi_new = phi - f / df
        if abs(phi_new - phi) < tol:
            return phi_new
        phi = phi_new
    return phi


def cycloid_radius(xf, yf):
    phi = cycloid_phi_f(xf, yf)
    return yf / (1.0 - math.cos(phi)), phi


def analytic_tf(xf=X_F, yf=Y_F, g=G):
    a, phi_f = cycloid_radius(xf, yf)
    return phi_f * math.sqrt(a / g)


def analytic_trajectories(t, xf=X_F, yf=Y_F, g=G):
    """Closed-form cycloid (x, y, v, θ) on an arbitrary time grid."""
    t = np.asarray(t, dtype=float)
    a, phi_f = cycloid_radius(xf, yf)
    scale = math.sqrt(a / g)
    phi = np.clip(t / scale, 0.0, phi_f)
    xpos = a * (phi - np.sin(phi))
    ypos = a * (1.0 - np.cos(phi))
    speed = 2.0 * math.sqrt(g * a) * np.abs(np.sin(phi / 2.0))
    theta = phi / 2.0
    return xpos, ypos, speed, theta


if __name__ == "__main__":
    print("analytic tf* =", ANALYTIC_TF, "xf, yf =", X_F, Y_F)
    sol, sys = solve()
    print(sol)
    xa, ya, va, tha = analytic_trajectories(sol.time)
    print("tf ocp/analytic", sol.tf, ANALYTIC_TF)
    print("x(tf), y(tf), v(tf)", sol.x[-1])
    print("θ(0), θ(tf)", sol.u[0, 0], sol.u[-1, 0], "analytic", tha[0], tha[-1])
    print("max |x-xa|", np.max(np.abs(sol.x[:, 0] - xa)))
    print("max |y-ya|", np.max(np.abs(sol.x[:, 1] - ya)))
