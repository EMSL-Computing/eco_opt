"""Goddard rocket free-final-time benchmark regression test.

Reproduces the MATLAB Yop benchmark
(``yoptimization/pages/benchmark/goddard_benchmark.md``) through the
installed ``eco_opt`` package and numerically compares against the reference
trajectory shipped with the benchmark (``work/goddard_benchmark/yop_goddard.mat``),
generated by the actual MATLAB Yop implementation with 59 control intervals.

Tolerances
----------
Yop's reference data has 60 sample points sampled directly at the NLP grid
nodes (interval boundaries) it used internally, matching eco_opt's own N=59
interval-boundary grid one-to-one (both use control_intervals=59 => 60
boundary points). Since both solvers use the same collocation scheme
(Radau/Legendre, degree 5) and starting point, we expect near machine-precision
agreement in the well-conditioned case (this problem is smooth and convex-ish
enough that IPOPT converges to the same local optimum from zero initial
guess). We assert:

* objective (final height) within 1e-3 relative tolerance,
* final time within 1e-3 relative tolerance,
* state trajectories (interpolated onto the reference's time grid, since in
  general node placement could differ) within 1.0 absolute/relative-scaled
  RMS tolerance per state (velocity ~ m/s, height ~ m, mass ~ kg) -- chosen
  generously relative to each state's magnitude to be robust to any minor
  formulation differences, while still failing on gross regressions.
* control trajectory RMS within 1e-2 (absolute; F in [0, 9.53]).

These are documented, not "solver succeeded" checks: values are asserted
against the actual reference numbers loaded from the .mat file.
"""

import os

import numpy as np
import pytest

scipy_io = pytest.importorskip("scipy.io")

import sys as _sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXAMPLES_DIR = os.path.join(HERE, "examples")
REFERENCE_MAT = os.path.join(HERE, "work", "goddard_benchmark", "yop_goddard.mat")


def _load_example():
    if EXAMPLES_DIR not in _sys.path:
        _sys.path.insert(0, EXAMPLES_DIR)
    import goddard_benchmark as gb

    return gb


@pytest.mark.skipif(not os.path.exists(REFERENCE_MAT), reason="reference .mat not available")
def test_goddard_benchmark_matches_yop_reference():
    gb = _load_example()
    sol, sys = gb.solve(control_intervals=59, polynomial_degree=5, tf_guess=200.0)

    assert sol.success, f"IPOPT did not report success: {sol.return_status}"

    ref = scipy_io.loadmat(REFERENCE_MAT)
    yop_t = ref["yop_t"].ravel()
    yop_x = ref["yop_x"]  # columns: v, h, m
    yop_u = ref["yop_u"].ravel()

    # -- objective / final time -------------------------------------------------
    yop_h_final = yop_x[-1, 1]
    yop_tf = yop_t[-1]

    obj_rel_err = abs(sol.objective - yop_h_final) / abs(yop_h_final)
    tf_rel_err = abs(sol.tf - yop_tf) / abs(yop_tf)

    assert obj_rel_err < 1e-3, f"objective rel error {obj_rel_err} too large"
    assert tf_rel_err < 1e-3, f"final time rel error {tf_rel_err} too large"

    # -- trajectories, interpolated onto the reference's time grid --------------
    v_interp = np.interp(yop_t, sol.time, sol.x[:, 0])
    h_interp = np.interp(yop_t, sol.time, sol.x[:, 1])
    m_interp = np.interp(yop_t, sol.time, sol.x[:, 2])
    u_time = sol.time[:-1]
    u_interp = np.interp(yop_t, u_time, sol.u[:, 0], right=sol.u[-1, 0])

    v_rms = np.sqrt(np.mean((v_interp - yop_x[:, 0]) ** 2))
    h_rms = np.sqrt(np.mean((h_interp - yop_x[:, 1]) ** 2))
    m_rms = np.sqrt(np.mean((m_interp - yop_x[:, 2]) ** 2))
    u_rms = np.sqrt(np.mean((u_interp - yop_u) ** 2))

    # Generous tolerances relative to each state's natural scale.
    assert v_rms < 1e-2, f"velocity RMS {v_rms} too large"
    assert h_rms < 1.0, f"height RMS {h_rms} too large (scale ~{np.max(np.abs(yop_x[:,1]))})"
    assert m_rms < 1e-2, f"mass RMS {m_rms} too large"
    assert u_rms < 1e-2, f"control RMS {u_rms} too large"

    # boundary conditions sanity checks
    assert abs(sol.x[0, 0]) < 1e-8       # v(0) == 0
    assert abs(sol.x[0, 1]) < 1e-8       # h(0) == 0
    assert abs(sol.x[0, 2] - 214.839) < 1e-6  # m(0) == m0
    assert abs(sol.x[-1, 2] - 67.9833) < 1e-4  # m(tf) == mf (active box-final bound)


def test_goddard_example_runs_standalone():
    gb = _load_example()
    sol, sys = gb.solve(control_intervals=20, polynomial_degree=3, tf_guess=200.0)
    assert sol.success
    assert sol.objective > 0
    assert sol.tf > 0
